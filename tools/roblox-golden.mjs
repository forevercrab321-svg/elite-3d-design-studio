// Golden values from the web game's own code, for roblox/tests/run.luau to compare the Luau port
// against (collision and growth maths). Usage: node tools/roblox-golden.mjs
import { createServer } from 'vite';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const server = await createServer({ root: resolve(root, 'game'), logLevel: 'error', server: { middlewareMode: true }, appType: 'custom' });
const { circleVsObb } = await server.ssrLoadModule(resolve(root, 'game/src/core/collision.ts'));
const growth = await server.ssrLoadModule(resolve(root, 'game/src/systems/growth.ts'));
await server.close();

let seed = 12345;
const rnd = () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648);
const collision = [];
for (let i = 0; i < 400; i++) {
  const b = { cx: rnd() * 20 - 10, cz: rnd() * 20 - 10, hx: 0.2 + rnd() * 4, hz: 0.2 + rnd() * 4, yaw: rnd() * 6.28 - 3.14 };
  const px = b.cx + (rnd() * 2 - 1) * 6, pz = b.cz + (rnd() * 2 - 1) * 6, r = 0.1 + rnd() * 3;
  const out = { nx: 0, nz: 0, depth: 0 };
  const hit = circleVsObb(px, pz, r, b, out);
  collision.push([px, pz, r, b.cx, b.cz, b.hx, b.hz, b.yaw, hit ? 1 : 0, out.nx, out.nz, out.depth]);
}
const masses = [5, 7.5, 12, 25.2, 60, 85, 200, 394, 1000, 3149, 9000, 14577, 60000, 320000, 2e6, 1.5e7];
const g = masses.map((m) => {
  const d = growth.diameterForMass(m);
  const cls = growth.classForPower(d);
  const p = growth.progressToNextClass(m);
  return [m, d, cls, growth.tierForClass(cls), p.nextClass ?? -1, p.nextMass ?? -1, p.fraction];
});
const lua = (rows) => rows.map((r) => `{ ${r.map((v) => String(+(+v).toPrecision(12))).join(', ')} }`).join(',\n\t');
writeFileSync(resolve(root, 'roblox/tests/golden.luau'), `--!nocheck\n-- GENERATED by tools/roblox-golden.mjs from the web game's code.\nreturn {\n collision = {\n\t${lua(collision)}\n },\n growth = {\n\t${lua(g)}\n },\n}\n`);
console.log('golden:', collision.length, 'collision cases (', collision.filter((c) => c[8]).length, 'hits ),', g.length, 'growth cases');

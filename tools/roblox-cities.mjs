// Turn the exported city layouts (roblox/assets/cities/*.json) into Luau modules
// roblox/src/shared/Cities/<id>.luau. Usage: node tools/roblox-cities.mjs
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const outDir = new URL('roblox/src/shared/Cities/', root);
mkdirSync(outDir, { recursive: true });
const n = (v) => String(+(+v).toFixed(3));
for (const f of readdirSync(new URL('roblox/assets/cities/', root))) {
  const c = JSON.parse(readFileSync(new URL(`roblox/assets/cities/${f}`, root), 'utf8'));
  const L = [];
  L.push('--!nocheck', `-- GENERATED by tools/roblox-cities.mjs from roblox/assets/cities/${f} (web city "${c.id}", seed ${c.seed}).`);
  L.push('-- Metres. objects: { type, x, y, z, yaw, colour, supports (1-based indices) | false, anchored }.', 'return {');
  L.push(`\tid = "${c.id}", name = ${JSON.stringify(c.name)}, nameZh = ${JSON.stringify(c.nameZh)}, level = ${c.level}, scenery = "${c.scenery.name}",`);
  L.push(`\tbounds = { minX = ${n(c.bounds.minX)}, maxX = ${n(c.bounds.maxX)}, minZ = ${n(c.bounds.minZ)}, maxZ = ${n(c.bounds.maxZ)} },`);
  L.push(`\tspawns = { ${c.spawns.map((s) => `{ x = ${n(s.x)}, z = ${n(s.z)}, heading = ${n(s.heading)} }`).join(', ')} },`);
  L.push(`\tstarterRing = ${c.starterRing ? `{ ${c.starterRing.map(([t, r, k]) => `{ "${t}", ${n(r)}, ${k} }`).join(', ')} }` : 'nil'},`);
  L.push(`\ttrees = { ${c.trees.map((t) => `{ ${n(t.x)}, ${n(t.y)}, ${n(t.z)} }`).join(', ')} },`, `\tcanopyScale = ${n(c.canopyScale)},`);
  L.push('\tobjects = {');
  for (const o of c.objects) {
    const sup = o.supports.length ? `{ ${o.supports.map((i) => i + 1).join(', ')} }` : 'false';
    L.push(`\t\t{ "${o.type}", ${n(o.x)}, ${n(o.y)}, ${n(o.z)}, ${n(o.yaw)}, "${o.color}", ${sup}, ${o.anchored} },`);
  }
  L.push('\t},');
  L.push(`\tblocks = { ${c.blocks.map((b) => `{ ${b.slice(0, 6).map(n).join(', ')}, "${b[6]}" }`).join(', ')} },`);
  L.push(`\tcolliders = { ${c.colliders.map((b) => `{ ${b.map(n).join(', ')} }`).join(', ')} },`);
  L.push(`\tground = { x0 = ${c.ground.x0}, z0 = ${c.ground.z0}, rows = {`);
  for (const r of c.ground.rows) L.push(`\t\t"${r}",`);
  L.push('\t} },', '}', '');
  writeFileSync(new URL(`${c.id}.luau`, outDir), L.join('\n'));
  console.log(c.id, c.objects.length, 'objects');
}

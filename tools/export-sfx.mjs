// Render the web game's sound effects into roblox/assets/audio/GrowSfx.ogg + roblox/src/shared/Sfx.luau
// (offset/length per sound for Sound.PlaybackRegion). Usage: node tools/export-sfx.mjs
import { createServer } from 'vite';
import { chromium } from 'playwright';
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
mkdirSync(resolve(root, 'roblox/assets/audio'), { recursive: true });
const server = await createServer({ configFile: resolve(root, 'tools/model-export/vite.config.mjs'), server: { port: 0 } });
await server.listen();
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage();
page.on('console', (m) => { if (m.type() === 'error') console.log('[page]', m.text().slice(0, 300)); });
await page.goto(`${server.resolvedUrls.local[0]}sfx.html`);
await page.waitForFunction(() => window.__EXPORT__ || window.__EXPORT_ERROR__, null, { timeout: 300000, polling: 500 });
const err = await page.evaluate(() => window.__EXPORT_ERROR__);
if (err) throw new Error(err);
const out = await page.evaluate(() => window.__EXPORT__);
await browser.close();
await server.close();
const wav = resolve(root, 'roblox/assets/audio/GrowSfx.wav');
writeFileSync(wav, Buffer.from(out.wav, 'base64'));
execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', wav, '-c:a', 'libvorbis', '-q:a', '6', resolve(root, 'roblox/assets/audio/GrowSfx.ogg')]);
const lines = ['--!strict', '-- GENERATED by tools/export-sfx.mjs: the web game\'s sound effects rendered into one sprite', '-- (assets/audio/GrowSfx.ogg). name = { offset s, length s }.', 'return {'];
for (const [k, [o, l]] of Object.entries(out.index)) lines.push(`\t${k} = { ${o}, ${l} },`);
lines.push('} :: { [string]: { number } }', '');
writeFileSync(resolve(root, 'roblox/src/shared/Sfx.luau'), lines.join('\n'));
console.log(`sfx: ${Object.keys(out.index).length} sounds, ${out.seconds.toFixed(1)} s`);

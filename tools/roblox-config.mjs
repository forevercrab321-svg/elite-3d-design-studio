// Export the web game's balance (game/src/config/*.ts) to roblox/src/shared/WebConfig.luau so the
// Roblox port uses the same numbers instead of copies. Usage: node tools/roblox-config.mjs
import { createServer } from 'vite';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const server = await createServer({ root: resolve(root, 'game'), logLevel: 'error', server: { middlewareMode: true }, appType: 'custom' });
const load = (p) => server.ssrLoadModule(resolve(root, 'game/src/config', p));
const growth = await load('growth.ts');
const { SIZE_CLASSES } = await load('classes.ts');
const { OBJECT_TYPES } = await load('objects.ts');
const { arenaConfig } = await load('arena.ts');
const { VEHICLES } = await load('vehicles.ts');
await server.close();

const vehicles = Object.fromEntries(Object.entries(VEHICLES).map(([k, v]) => [k, v.stats ?? v]));
const data = {
  growth: growth.growthConfig,
  movement: growth.movementConfig,
  collection: growth.collectionConfig,
  camera: growth.cameraConfig,
  feel: growth.feelConfig,
  classes: SIZE_CLASSES,
  objects: OBJECT_TYPES,
  arena: arenaConfig,
  vehicles,
};

const ident = /^[A-Za-z_][A-Za-z0-9_]*$/;
function lua(v, indent) {
  const pad = '\t'.repeat(indent + 1);
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'number') return Number.isFinite(v) ? String(+v.toPrecision(12)) : '0';
  if (typeof v === 'boolean') return String(v);
  if (typeof v === 'string') return JSON.stringify(v);
  if (typeof v === 'function') return 'nil';
  if (Array.isArray(v)) {
    if (v.every((x) => typeof x !== 'object' || x === null)) return `{ ${v.map((x) => lua(x, indent)).join(', ')} }`;
    return `{\n${v.map((x) => pad + lua(x, indent + 1)).join(',\n')},\n${'\t'.repeat(indent)}}`;
  }
  if (typeof v === 'object') {
    if (v.isColor || v.isVector3) return 'nil';
    const entries = Object.entries(v).filter(([, x]) => typeof x !== 'function');
    if (!entries.length) return '{}';
    return `{\n${entries.map(([k, x]) => `${pad}${ident.test(k) ? k : `[${JSON.stringify(k)}]`} = ${lua(x, indent + 1)}`).join(',\n')},\n${'\t'.repeat(indent)}}`;
  }
  return 'nil';
}

const out = `--!nocheck
-- GENERATED by tools/roblox-config.mjs from game/src/config/*.ts — do not edit by hand.
-- The web game's balance in its own units (metres, kilograms, seconds). Convert to studs with
-- Config.STUDS_PER_METER where needed.
return ${lua(data, 0)}
`;
writeFileSync(resolve(root, 'roblox/src/shared/WebConfig.luau'), out);
console.log('WebConfig.luau:', Object.keys(OBJECT_TYPES).length, 'objects,', SIZE_CLASSES.length, 'classes, vehicles', Object.keys(vehicles).join('/'));

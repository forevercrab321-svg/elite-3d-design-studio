// Generate roblox/src/shared/ModelInfo.luau from roblox/assets/manifest.json: per model its size
// in metres and, per mesh, the colour/material/transparency the loader re-applies after import.
// Usage: node tools/roblox-modelinfo.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('roblox/assets/manifest.json', root), 'utf8'));
// City scenery GLBs (tools/export-city.mjs) are models too: their meshes and box come from the layouts.
let tinted = new Set();
for (const f of readdirSync(new URL('roblox/assets/cities/', root))) {
  const c = JSON.parse(readFileSync(new URL(`roblox/assets/cities/${f}`, root), 'utf8'));
  const min = c.sceneryBox.min, max = c.sceneryBox.max;
  manifest[c.scenery.name] = { group: 'scenery', size: max.map((v, i) => +(v - min[i]).toFixed(3)), min: min.map((v) => +v.toFixed(3)), meshes: c.scenery.meshes };
  tinted = new Set(c.tinted);
}

// Web material role (MaterialLibrary name) → Roblox material, so surfaces keep their texture
// language (brick, concrete, rubber, metal…) instead of all being flat plastic.
const ROLE_MATERIAL = {
  propBrick: 'Brick', brick: 'Brick', darkBrick: 'Brick',
  concreteProp: 'Concrete', concrete: 'Concrete', plaster: 'Concrete', curb: 'Concrete',
  stone: 'Limestone', sidewalk: 'Pavement', asphalt: 'Asphalt', gravel: 'Pebble',
  tread: 'Rubber', rubber: 'Rubber',
  steel: 'Metal', steelDark: 'Metal', aluminium: 'Metal', chrome: 'Metal', metals: 'Metal', metalLight: 'Metal',
  copper: 'Metal', roofMetal: 'CorrodedMetal', corrugated: 'CorrodedMetal', Player_Gunmetal: 'Metal',
  glass: 'Glass', glassTint: 'Glass', clearGlass: 'Glass', windowGlass: 'Glass', shopGlass: 'Glass',
  wood: 'WoodPlanks', timber: 'Wood', fabric: 'Fabric', velvet: 'Fabric', cardboard: 'Cardboard',
  lamps: 'Neon', headlight: 'Neon', taillight: 'Neon', screen: 'Neon', lampGlow: 'Neon',
  plastic: 'Plastic',
};

function material(m) {
  if (m.emissive) return 'Neon';
  if (ROLE_MATERIAL[m.role]) return ROLE_MATERIAL[m.role];
  if (m.opacity < 0.99) return 'Glass';
  if (m.metalness >= 0.6) return 'Metal';
  return 'SmoothPlastic';
}

const num = (n) => +n.toFixed(3);
const lines = [
  '--!strict',
  '-- GENERATED by tools/roblox-modelinfo.mjs from roblox/assets/manifest.json — do not edit by hand.',
  '-- size / min: bounding box in metres (web units) and its low corner relative to the model origin;',
  '-- meshes: per MeshPart name {hex colour, material, transparency, tint = takes the instance colour}.',
  '',
  'export type MeshInfo = { c: string, m: string, t: number, tint: boolean?, r: string? }',
  'export type Info = { group: string, size: Vector3, min: Vector3, meshes: { [string]: MeshInfo } }',
  '',
  'return {',
];
for (const [name, v] of Object.entries(manifest)) {
  const meshes = v.meshes
    .map((m) => `[${JSON.stringify(m.name)}] = { c = "${m.color}", m = "${material(m)}", t = ${num(1 - m.opacity)}${tinted.has(m.role) && v.group === 'object' ? ', tint = true' : ''}${v.group === 'machine' ? `, r = "${m.role}"` : ''} }`)
    .join(', ');
  lines.push(`\t${name} = { group = "${v.group}", size = Vector3.new(${v.size.map(num).join(', ')}), min = Vector3.new(${(v.min ?? [0, 0, 0]).map(num).join(', ')}), meshes = { ${meshes} } },`);
}
lines.push('} :: { [string]: Info }', '');
writeFileSync(new URL('roblox/src/shared/ModelInfo.luau', root), lines.join('\n'));
console.log(Object.keys(manifest).length, 'models');
